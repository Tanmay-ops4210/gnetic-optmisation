class NumberedCanvas(canvas.Canvas):
    """
    Two-pass canvas to dynamically compute total pages and draw consistent
    running headers and 'Page X of Y' footers.
    """
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, total_pages: int):
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#64748b"))

        # Header (pages > 1)
        if self._pageNumber > 1:
            self.drawString(36, 762, "AutoML Genetic Optimizer — Optimization Report")
            self.setStrokeColor(colors.HexColor("#cbd5e1"))
            self.setLineWidth(0.5)
            self.line(36, 756, 576, 756)

        # Footer (all pages)
        footer_text = f"Page {self._pageNumber} of {total_pages}"
        self.drawRightString(576, 25, footer_text)
        self.drawString(36, 25, "Confidential — Generated by AutoML Genetic Optimizer")
        self.setStrokeColor(colors.HexColor("#e2e8f0"))
        self.setLineWidth(0.5)
        self.line(36, 35, 576, 35)

        self.restoreState()


class ChartGenerator:
    """
    Renders high-resolution chart images in-memory as BytesIO buffers
    for embedding into PDF documents.
    """
    PRIMARY_COLOR = "#4f46e5"     # Indigo
    ACCENT_COLOR = "#10b981"      # Emerald
    SECONDARY_COLOR = "#f59e0b"   # Amber
    MUTED_COLOR = "#94a3b8"       # Slate
    DARK_TEXT = "#1e293b"

    @classmethod
    def create_model_comparison_chart(cls, comparison_data: List[Dict[str, Any]], metric: str) -> io.BytesIO:
        if not comparison_data:
            return None

        models = [item.get("model", "Unknown") for item in comparison_data]
        scores = [float(item.get("score", 0.0)) for item in comparison_data]
        is_opt = [("Optimized" in item.get("model", "") or item.get("type") == "optimized") for item in comparison_data]

        fig, ax = plt.subplots(figsize=(6.5, 3.2), dpi=200)
        bar_colors = [cls.ACCENT_COLOR if opt else cls.PRIMARY_COLOR for opt in is_opt]

        y_pos = np.arange(len(models))
        bars = ax.barh(y_pos, scores, color=bar_colors, edgecolor="#312e81", height=0.55)

        ax.set_yticks(y_pos)
        ax.set_yticklabels(models, fontsize=9, fontweight="medium", color=cls.DARK_TEXT)
        ax.invert_yaxis()  # Best on top if ordered
        ax.set_xlabel(f"Score ({metric.upper()})", fontsize=9, color=cls.DARK_TEXT, labelpad=6)
        ax.set_title("Model Performance Benchmark Comparison", fontsize=11, fontweight="bold", pad=10, color=cls.DARK_TEXT)
        ax.grid(axis="x", linestyle="--", alpha=0.5, color="#cbd5e1")
        ax.set_axisbelow(True)

        for spine in ["top", "right"]:
            ax.spines[spine].set_visible(False)
        for spine in ["left", "bottom"]:
            ax.spines[spine].set_color("#94a3b8")

        # Label values on bars
        for bar in bars:
            width = bar.get_width()
            ax.text(
                width + (max(scores) * 0.02 if max(scores) > 0 else 0.01),
                bar.get_y() + bar.get_height() / 2,
                f"{width:.4f}",
                va="center", ha="left", fontsize=8, color="#0f172a", fontweight="bold"
            )

        plt.tight_layout()
        buf = io.BytesIO()
        plt.savefig(buf, format="png", bbox_inches="tight")
        plt.close(fig)
        buf.seek(0)
        return buf

    @classmethod
    def create_fitness_history_chart(cls, fitness_history: List[Dict[str, Any]]) -> io.BytesIO:
        if not fitness_history or len(fitness_history) < 2:
            return None

        generations = [item.get("generation", idx) for idx, item in enumerate(fitness_history)]
        bests = [float(item.get("best", 0.0)) for item in fitness_history]
        avgs = [float(item.get("avg", 0.0)) for item in fitness_history]

        fig, ax = plt.subplots(figsize=(6.5, 3.0), dpi=200)

        ax.plot(generations, bests, label="Best Fitness", color=cls.ACCENT_COLOR, linewidth=2.2, marker="o", markersize=3.5)
        ax.plot(generations, avgs, label="Population Average", color=cls.PRIMARY_COLOR, linewidth=1.8, linestyle="--")

        ax.set_xlabel("Generation", fontsize=9, color=cls.DARK_TEXT, labelpad=5)
        ax.set_ylabel("Fitness Score", fontsize=9, color=cls.DARK_TEXT, labelpad=5)
        ax.set_title("Evolutionary Fitness Trajectory (Generations vs Score)", fontsize=11, fontweight="bold", pad=10, color=cls.DARK_TEXT)
        ax.legend(loc="lower right", frameon=True, facecolor="#ffffff", edgecolor="#cbd5e1", fontsize=8)
        ax.grid(True, linestyle="--", alpha=0.5, color="#cbd5e1")
        ax.set_axisbelow(True)

        for spine in ["top", "right"]:
            ax.spines[spine].set_visible(False)
        for spine in ["left", "bottom"]:
            ax.spines[spine].set_color("#94a3b8")

        plt.tight_layout()
        buf = io.BytesIO()
        plt.savefig(buf, format="png", bbox_inches="tight")
        plt.close(fig)
        buf.seek(0)
        return buf

    @classmethod
    def create_feature_importance_chart(cls, feature_importance: Dict[str, float]) -> io.BytesIO:
        if not feature_importance:
            return None

        # Sort top 10 features
        sorted_feats = sorted(feature_importance.items(), key=lambda x: x[1], reverse=True)[:10]
        feats = [f[0] for f in sorted_feats]
        vals = [f[1] for f in sorted_feats]

        fig, ax = plt.subplots(figsize=(6.5, 3.2), dpi=200)
        y_pos = np.arange(len(feats))

        ax.barh(y_pos, vals, color=cls.PRIMARY_COLOR, edgecolor="#3730a3", height=0.55)
        ax.set_yticks(y_pos)
        ax.set_yticklabels(feats, fontsize=8.5, color=cls.DARK_TEXT)
        ax.invert_yaxis()
        ax.set_xlabel("Relative Importance", fontsize=9, color=cls.DARK_TEXT, labelpad=5)
        ax.set_title("Top 10 Feature Importances", fontsize=11, fontweight="bold", pad=10, color=cls.DARK_TEXT)
        ax.grid(axis="x", linestyle="--", alpha=0.5, color="#cbd5e1")
        ax.set_axisbelow(True)

        for spine in ["top", "right"]:
            ax.spines[spine].set_visible(False)
        for spine in ["left", "bottom"]:
            ax.spines[spine].set_color("#94a3b8")

        for i, val in enumerate(vals):
            ax.text(val + (max(vals) * 0.02 if max(vals) > 0 else 0.005), i, f"{val:.3f}", va="center", ha="left", fontsize=8, color="#0f172a")

        plt.tight_layout()
        buf = io.BytesIO()
        plt.savefig(buf, format="png", bbox_inches="tight")
        plt.close(fig)
        buf.seek(0)
        return buf

    @classmethod
    def create_confusion_matrix_chart(cls, matrix: List[List[int]], class_labels: Optional[List[str]]) -> io.BytesIO:
        if not matrix or len(matrix) == 0:
            return None

        cm = np.array(matrix)
        fig, ax = plt.subplots(figsize=(4.8, 3.2), dpi=200)

        im = ax.imshow(cm, interpolation="nearest", cmap="Blues")
        fig.colorbar(im, ax=ax, fraction=0.046, pad=0.04)

        labels = class_labels if (class_labels and len(class_labels) == len(cm)) else [str(i) for i in range(len(cm))]
        ax.set(
            xticks=np.arange(cm.shape[1]),
            yticks=np.arange(cm.shape[0]),
            xticklabels=labels,
            yticklabels=labels,
            ylabel="Actual Class",
            xlabel="Predicted Class"
        )
        ax.set_title("Confusion Matrix Evaluation", fontsize=10, fontweight="bold", pad=8, color=cls.DARK_TEXT)

        thresh = cm.max() / 2.0 if cm.max() > 0 else 1
        for i in range(cm.shape[0]):
            for j in range(cm.shape[1]):
                ax.text(
                    j, i, format(cm[i, j], "d"),
                    ha="center", va="center",
                    color="white" if cm[i, j] > thresh else "#0f172a",
                    fontweight="bold", fontsize=9
                )

        plt.tight_layout()
        buf = io.BytesIO()
        plt.savefig(buf, format="png", bbox_inches="tight")
        plt.close(fig)
        buf.seek(0)
        return buf


class BaseReportMaker(ABC):
    """
    Abstract base class establishing the contract for all report generation engines.
    """
    def __init__(self, result: Dict[str, Any], metadata: Optional[Dict[str, Any]] = None):
        self.result = result
        self.metadata = metadata or {}

    @abstractmethod
    def generate(self) -> bytes:
        """Generates the report and returns raw document bytes."""
        pass


class PDFReportMaker(BaseReportMaker):
    """
    Professional PDF Report Generator creating a comprehensive, beautifully styled
    diagnostic report of the AutoML optimization session with embedded charts,
    hyperparameter specifications, and technical explanations.
    """
    def __init__(self, result: Dict[str, Any], metadata: Optional[Dict[str, Any]] = None):
        super().__init__(result, metadata)
        self.styles = getSampleStyleSheet()
        self._init_custom_styles()

    def _init_custom_styles(self):
        self.styles.add(ParagraphStyle(
            'ReportTitle',
            parent=self.styles['Heading1'],
            fontName='Helvetica-Bold',
            fontSize=22,
            leading=26,
            textColor=colors.HexColor('#1e1b4b'),
            spaceAfter=4,
        ))
        self.styles.add(ParagraphStyle(
            'ReportSubtitle',
            parent=self.styles['Normal'],
            fontName='Helvetica',
            fontSize=10,
            leading=14,
            textColor=colors.HexColor('#64748b'),
            spaceAfter=12,
        ))
        self.styles.add(ParagraphStyle(
            'SectionHeader',
            parent=self.styles['Heading2'],
            fontName='Helvetica-Bold',
            fontSize=13,
            leading=17,
            textColor=colors.HexColor('#312e81'),
            spaceBefore=14,
            spaceAfter=6,
        ))
        self.styles.add(ParagraphStyle(
            'SectionSubHeader',
            parent=self.styles['Heading3'],
            fontName='Helvetica-Bold',
            fontSize=10.5,
            leading=14,
            textColor=colors.HexColor('#1e293b'),
            spaceBefore=8,
            spaceAfter=4,
        ))
        self.styles.add(ParagraphStyle(
            'Body',
            parent=self.styles['Normal'],
            fontName='Helvetica',
            fontSize=9,
            leading=13.5,
            textColor=colors.HexColor('#334155'),
            spaceAfter=6,
        ))
        self.styles.add(ParagraphStyle(
            'ExplanationBox',
            parent=self.styles['Normal'],
            fontName='Helvetica-Oblique',
            fontSize=8.5,
            leading=12.5,
            textColor=colors.HexColor('#475569'),
            spaceAfter=6,
        ))
        self.styles.add(ParagraphStyle(
            'TableText',
            parent=self.styles['Normal'],
            fontName='Helvetica',
            fontSize=8.5,
            leading=11,
            textColor=colors.HexColor('#1e293b'),
        ))
        self.styles.add(ParagraphStyle(
            'TableTextBold',
            parent=self.styles['Normal'],
            fontName='Helvetica-Bold',
            fontSize=8.5,
            leading=11,
            textColor=colors.HexColor('#1e1b4b'),
        ))
        self.styles.add(ParagraphStyle(
            'CodeText',
            parent=self.styles['Normal'],
            fontName='Courier',
            fontSize=8,
            leading=10,
            textColor=colors.HexColor('#312e81'),
        ))

    def generate(self) -> bytes:
        pdf_buffer = io.BytesIO()
        doc = SimpleDocTemplate(
            pdf_buffer,
            pagesize=letter,
            leftMargin=36,
            rightMargin=36,
            topMargin=46,
            bottomMargin=46
        )

        story = []

        # 1. Header Banner & Title
        story.extend(self._build_header_section())
        story.append(Spacer(1, 10))

        # 2. Executive Summary Metrics Table
        story.extend(self._build_executive_summary())
        story.append(Spacer(1, 14))

        # 3. Best Model Hyperparameter Configuration
        story.extend(self._build_hyperparameter_section())
        story.append(Spacer(1, 14))

        # 4. Model Benchmark Comparison (Chart + Explanation)
        story.extend(self._build_model_comparison_section())
        story.append(Spacer(1, 14))

        # 5. Evolutionary Search Trajectory (Chart + Explanation)
        story.extend(self._build_evolutionary_progress_section())
        story.append(Spacer(1, 14))

        # 6. Interpretability & Diagnostics (Feature Importance / Confusion Matrix)
        story.extend(self._build_diagnostics_section())

        doc.build(story, canvasmaker=NumberedCanvas)
        pdf_buffer.seek(0)
        return pdf_buffer.getvalue()

    def _build_header_section(self) -> List[Any]:
        opt_id = self.result.get('id', 'Unknown')
        created_at = self.metadata.get('created_at', datetime.now().strftime('%Y-%m-%d %H:%M:%S'))
        dataset_name = self.metadata.get('dataset_name', 'Uploaded Dataset')

        elements = [
            Paragraph("AutoML Genetic Optimization Report", self.styles['ReportTitle']),
            Paragraph(
                f"Generated on {created_at} &bull; Run ID: <code>{opt_id[:12]}...</code> &bull; Dataset: <b>{dataset_name}</b>",
                self.styles['ReportSubtitle']
            ),
            HRFlowable(width="100%", thickness=1.5, color=colors.HexColor('#4f46e5'), spaceAfter=8)
        ]
        return elements

    def _build_executive_summary(self) -> List[Any]:
        best_model = self.result.get('best_model', 'N/A')
        metric = self.result.get('metric', 'accuracy').upper()
        best_score = float(self.result.get('best_score', 0.0))
        baseline_score = float(self.result.get('baseline_score', 0.0))
        improvement = float(self.result.get('improvement', 0.0))
        prob_type = str(self.result.get('problem_type', 'classification')).capitalize()
        duration = float(self.result.get('duration', 0.0))
        generations = self.result.get('total_generations', 0)
        pop_size = self.result.get('population_size', 0)
        models_tested = self.result.get('models_tested', 0)

        data = [
            [
                Paragraph("<b>Champion Model</b>", self.styles['TableTextBold']),
                Paragraph(f"<b>{best_model}</b>", self.styles['TableTextBold']),
                Paragraph("<b>Problem Type</b>", self.styles['TableTextBold']),
                Paragraph(prob_type, self.styles['TableText']),
            ],
            [
                Paragraph(f"<b>Optimized {metric}</b>", self.styles['TableTextBold']),
                Paragraph(f"<font color='#059669'><b>{best_score:.4f}</b></font>", self.styles['TableTextBold']),
                Paragraph("<b>Baseline Score</b>", self.styles['TableTextBold']),
                Paragraph(f"{baseline_score:.4f}", self.styles['TableText']),
            ],
            [
                Paragraph("<b>Relative Gain</b>", self.styles['TableTextBold']),
                Paragraph(f"<font color='#059669'><b>+{improvement:.2f}%</b></font>", self.styles['TableTextBold']),
                Paragraph("<b>Duration</b>", self.styles['TableTextBold']),
                Paragraph(f"{duration:.1f}s", self.styles['TableText']),
            ],
            [
                Paragraph("<b>Generations / Pop</b>", self.styles['TableTextBold']),
                Paragraph(f"{generations} gens &bull; {pop_size} pop", self.styles['TableText']),
                Paragraph("<b>Models Evaluated</b>", self.styles['TableTextBold']),
                Paragraph(f"{models_tested} candidates", self.styles['TableText']),
            ]
        ]

        table = Table(data, colWidths=[130, 140, 130, 140])
        table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor('#f8fafc')),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#e2e8f0')),
            ('PADDING', (0, 0), (-1, -1), 5),
            ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ]))

        return [
            Paragraph("Executive Optimization Summary", self.styles['SectionHeader']),
            table
        ]

    def _build_hyperparameter_section(self) -> List[Any]:
        best_params = self.result.get('best_params', {})
        if not best_params:
            return []

        elements = [
            Paragraph("Champion Hyperparameter Configuration", self.styles['SectionHeader']),
            Paragraph(
                "These hyperparameters represent the fittest individual evolved through genetic selection, crossover, and mutation:",
                self.styles['Body']
            )
        ]

        param_rows = [
            [
                Paragraph("<b>Parameter</b>", self.styles['TableTextBold']),
                Paragraph("<b>Tuned Value</b>", self.styles['TableTextBold'])
            ]
        ]

        for k, v in best_params.items():
            param_rows.append([
                Paragraph(f"<code>{k}</code>", self.styles['TableText']),
                Paragraph(f"<code>{str(v)}</code>", self.styles['CodeText'])
            ])

        table = Table(param_rows, colWidths=[240, 300])
        table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#ede9fe')),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#e2e8f0')),
            ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor('#f8fafc')]),
            ('PADDING', (0, 0), (-1, -1), 4.5),
        ]))

        elements.append(table)
        return elements

    def _build_model_comparison_section(self) -> List[Any]:
        comparison = self.result.get('model_comparison', [])
        metric = self.result.get('metric', 'accuracy')

        elements = [
            Paragraph("1. Multi-Model Benchmark Comparison", self.styles['SectionHeader']),
            Paragraph(
                "Prior to and following evolutionary tuning, baseline algorithm families were evaluated using cross-validation to establish performance baselines.",
                self.styles['Body']
            )
        ]

        chart_buf = ChartGenerator.create_model_comparison_chart(comparison, metric)
        if chart_buf:
            img = Image(chart_buf, width=6.5 * inch, height=3.2 * inch)
            elements.append(img)
            elements.append(Spacer(1, 6))

        # Analytical explanation
        explanation = (
            "<b>Graph Explanation:</b> The benchmark bar chart contrasts the validation scores achieved by different machine learning families. "
            "The top-performing algorithm underwent hyperparameter evolution, outperforming default parameter baselines. "
            "Diversity in model structures ensures resilient model selection tailored specifically to the dataset's distribution."
        )
        elements.append(Paragraph(explanation, self.styles['ExplanationBox']))
        return elements

    def _build_evolutionary_progress_section(self) -> List[Any]:
        history = self.result.get('fitness_history', [])
        elements = [
            Paragraph("2. Evolutionary Trajectory & Convergence", self.styles['SectionHeader']),
            Paragraph(
                "The Genetic Algorithm maintains a population of candidate configurations. In each generation, top individuals are selected for crossover and mutation.",
                self.styles['Body']
            )
        ]

        chart_buf = ChartGenerator.create_fitness_history_chart(history)
        if chart_buf:
            img = Image(chart_buf, width=6.5 * inch, height=3.0 * inch)
            elements.append(img)
            elements.append(Spacer(1, 6))

        explanation = (
            "<b>Graph Explanation:</b> The trajectory plot demonstrates evolutionary optimization over generations. "
            "The solid green curve tracks the peak fitness in the population, showing progressive metric discovery. "
            "The dashed purple curve tracks population average fitness; narrowing the gap between best and average indicates convergence toward an optimal hyperparameter regime."
        )
        elements.append(Paragraph(explanation, self.styles['ExplanationBox']))
        return elements

    def _build_diagnostics_section(self) -> List[Any]:
        elements = [
            Paragraph("3. Model Interpretability & Diagnostics", self.styles['SectionHeader'])
        ]

        has_any = False
        feat_imp = self.result.get('feature_importance')
        if feat_imp:
            has_any = True
            chart_buf = ChartGenerator.create_feature_importance_chart(feat_imp)
            if chart_buf:
                elements.append(Paragraph("Feature Importance Ranking", self.styles['SectionSubHeader']))
                img = Image(chart_buf, width=6.5 * inch, height=3.2 * inch)
                elements.append(img)
                elements.append(Spacer(1, 4))
                exp = (
                    "<b>Graph Explanation:</b> Relative feature importances quantify each input attribute's contribution "
                    "to the champion model's decision boundaries. Features at the top carry the strongest predictive signal."
                )
                elements.append(Paragraph(exp, self.styles['ExplanationBox']))
                elements.append(Spacer(1, 10))

        cm = self.result.get('confusion_matrix')
        if cm:
            has_any = True
            chart_buf = ChartGenerator.create_confusion_matrix_chart(cm, self.result.get('class_labels'))
            if chart_buf:
                elements.append(Paragraph("Confusion Matrix Classification Diagnostics", self.styles['SectionSubHeader']))
                img = Image(chart_buf, width=4.8 * inch, height=3.2 * inch)
                elements.append(img)
                elements.append(Spacer(1, 4))
                exp = (
                    "<b>Graph Explanation:</b> The confusion matrix reveals true vs predicted class distributions. "
                    "Diagonal cells represent accurate predictions, whereas off-diagonal elements indicate specific misclassification patterns."
                )
                elements.append(Paragraph(exp, self.styles['ExplanationBox']))

        if not has_any:
            elements.append(Paragraph(
                "Diagnostic visualizations are automatically tailored to the problem type and model architecture.",
                self.styles['Body']
            ))

        return elements
